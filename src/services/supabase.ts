/**
 * 2. PORTFOLIO (جدول معرض الأعمال)
 */

export async function fetchPortfolioFromSupabase(): Promise<{
  success: boolean;
  data: PortfolioItem[];
  isFromSupabase: boolean;
  error?: any;
}> {
  try {
    const { data, error } = await supabase
      .from('portfolio')
      .select('id, image_url, category')
      .order('id', { ascending: false });

    if (error) {
      console.warn('Supabase fetch portfolio error:', error.message);
      return {
        success: false,
        data: PORTFOLIO_ITEMS,
        isFromSupabase: false,
        error,
      };
    }

    if (data && data.length > 0) {
      const categoryLabels: Record<string, string> = {
        paints: 'دهانات وتشطيبات',
        wood_alternative: 'بديل خشب',
        marble_alternative: 'بديل رخام',
        stone_alternative: 'بديل حجر',
        chipboard: 'شيبورد و MDF',
      };

      const mapped: PortfolioItem[] = data.map((row) => ({
        id: `supabase-port-${row.id}`,
        title: `تشطيب ${categoryLabels[row.category] || row.category} - الرضا`,
        category: row.category,
        categoryName: categoryLabels[row.category] || 'تشطيبات مميزة',
        location: 'القاهرة الكبرى',
        imageUrl: row.image_url,
        paintUsed: 'تشطيب فندقي معتمد وخامات عالية الجودة',
        colorCode: `SB-${row.id}`,
        description: 'عمل حقيقي منفذ بأيدي فريق الرضا للدهانات والديكورات بأعلى دقة وتناسق.',
      }));

      // Filter out any unsplash demo photos, keep only real Abo Reda photos
      const filtered = [...mapped, ...PORTFOLIO_ITEMS].filter(
        (item) => !item.imageUrl.includes('unsplash.com')
      );

      return {
        success: true,
        data: filtered,
        isFromSupabase: true,
      };
    }

    return {
      success: true,
      data: PORTFOLIO_ITEMS.filter((item) => !item.imageUrl.includes('unsplash.com')),
      isFromSupabase: false,
    };
  } catch (err: any) {
    console.error('Exception fetching portfolio from Supabase:', err);
    return {
      success: false,
      data: PORTFOLIO_ITEMS,
      isFromSupabase: false,
      error: err,
    };
  }
}

/**
 * 3. COMPLAINTS (جدول الشكاوى والاستفسارات)
 */

export async function submitComplaintToSupabase(
  customerName: string,
  phone: string,
  complaintText: string
): Promise<{ success: boolean; data?: any; error?: any }> {
  try {
    const { data, error } = await supabase
      .from('complaints')
      .insert([
        {
          customer_name: customerName,
          phone,
          complaint_text: complaintText,
        },
      ])
      .select();

    if (error) {
      console.warn('Error inserting complaint to Supabase:', error.message);
      return { success: false, error: error.message };
    }

    return { success: true, data };
  } catch (err: any) {
    console.error('Exception submitting complaint to Supabase:', err);
    return { success: false, error: err.message || 'حدث خطأ أثناء حفظ الشكوى' };
  }
}

/**
 * 4. COMPANY COVERAGE (جدول معدل تغطية البستلة لكل شركة)
 */

export async function fetchCompanyCoverageFromSupabase(): Promise<{
  success: boolean;
  data: SupabaseCompanyCoverage[];
  coverageMap: Record<string, number>;
  isFromSupabase: boolean;
  error?: any;
}> {
  try {
    const { data, error } = await supabase
      .from('company_coverage')
      .select('id, company_name, coverage_per_bucket')
      .order('id', { ascending: true });

    if (error) {
      console.warn('Supabase fetch company_coverage error:', error.message);
      return {
        success: false,
        data: [],
        coverageMap: DEFAULT_COMPANY_COVERAGE,
        isFromSupabase: false,
        error,
      };
    }

    if (data && data.length > 0) {
      const coverageMap: Record<string, number> = { ...DEFAULT_COMPANY_COVERAGE };
      const list: SupabaseCompanyCoverage[] = data.map((row) => {
        const val = Number(row.coverage_per_bucket) || 25;
        coverageMap[row.company_name] = val;
        // Also map English ID keys if matched
        const n = row.company_name.toLowerCase();
        if (n.includes('جوتن') || n.includes('jotun')) coverageMap['jotun'] = val;
        if (n.includes('glc')) coverageMap['glc'] = val;
        if (n.includes('سايبس') || n.includes('sipes')) coverageMap['sipes'] = val;
        if (n.includes('باكين') || n.includes('pachin')) coverageMap['pachin'] = val;
        if (n.includes('جزيرة') || n.includes('aljazeera')) coverageMap['aljazeera'] = val;
        return {
          id: row.id,
          company_name: row.company_name,
          coverage_per_bucket: val,
        };
      });

      return {
        success: true,
        data: list,
        coverageMap,
        isFromSupabase: true,
      };
    }

    // Table exists but is empty -> seed initial defaults
    await seedInitialCompanyCoverageToSupabase();

    return {
      success: true,
      data: [],
      coverageMap: DEFAULT_COMPANY_COVERAGE,
      isFromSupabase: false,
    };
  } catch (err: any) {
    console.error('Exception fetching company_coverage from Supabase:', err);
    return {
      success: false,
      data: [],
      coverageMap: DEFAULT_COMPANY_COVERAGE,
      isFromSupabase: false,
      error: err,
    };
  }
}

