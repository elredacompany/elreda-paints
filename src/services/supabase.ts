/**
 * 1. PRICES (جدول الأسعار)
 */

export async function fetchPricesFromSupabase(): Promise<{
  success: boolean;
  data: PaintBrandOption[];
  isFromSupabase: boolean;
  error?: any;
}> {
  try {
    const { data, error } = await supabase
      .from('prices')
      .select('id, company_name, product_name, price')
      .order('id', { ascending: true });

    if (error) {
      console.warn('Supabase fetch prices error:', error.message);
      return {
        success: false,
        data: PAINT_COMPANY_OPTIONS,
        isFromSupabase: false,
        error,
      };
    }

    if (data && data.length > 0) {
      // Convert database rows to PaintBrandOption
      const mapped: PaintBrandOption[] = data.map((row) => ({
        id: `supabase-${row.id}`,
        name: `${row.company_name} ${row.product_name}`,
        brand: row.company_name,
        price: Number(row.price),
        description: `سعر البستلة البيضاء المسجل في سوبابيس (${row.company_name})`,
      }));

      return {
        success: true,
        data: mapped,
        isFromSupabase: true,
      };
    }

    // Table exists but empty -> try to seed initial prices
    await seedInitialPricesToSupabase();

    return {
      success: true,
      data: PAINT_COMPANY_OPTIONS,
      isFromSupabase: false,
    };
  } catch (err: any) {
    console.error('Exception fetching prices from Supabase:', err);
    return {
      success: false,
      data: PAINT_COMPANY_OPTIONS,
      isFromSupabase: false,
      error: err,
    };
  }
}

