/**
 * Quick connection check
 */
export async function testSupabaseConnection(): Promise<{
  connected: boolean;
  message: string;
  details?: any;
}> {
  try {
    const { data, error } = await supabase.from('prices').select('id').limit(1);

    if (error) {
      // Check if table missing (PGRST204 or 42P01)
      if (error.code === '42P01' || error.message?.includes('relation "prices" does not exist')) {
        return {
          connected: true,
          message: 'تم الاتصال بسوبابيس بنجاح، ولكن الجداول تحتاج لتشغيل كود الـ SQL المرفق لإنشائها.',
          details: error,
        };
      }
      return {
        connected: false,
        message: `تعذر الوصول للجداول: ${error.message}`,
        details: error,
      };
    }

    return {
      connected: true,
      message: 'الاتصال بسوبابيس نشط ويعمل بنجاح 100%',
      details: data,
    };
  } catch (err: any) {
    return {
      connected: false,
      message: `فشل الاتصال: ${err.message}`,
      details: err,
    };
  }
}
